package com.yerkkee.utils;

import com.yerkkee.config.TestConfig;
import lombok.extern.slf4j.Slf4j;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Properties;

/**
 * Writes environment.properties into the Allure results directory before tests start,
 * so the report shows which browser / URL / Java the run used.
 *
 * <p>Failure categories are configured in allurerc.yml (Allure 3 reads them from its config,
 * not from categories.json in the results directory).
 */
@Slf4j
public final class AllureEnvironmentWriter {

    private AllureEnvironmentWriter() {
        throw new UnsupportedOperationException("Utility class");
    }

    public static void write() {
        Path resultsDir = Paths.get(System.getProperty("allure.results.directory", "allure-results"));
        try {
            Files.createDirectories(resultsDir);
            writeEnvironment(resultsDir.resolve("environment.properties"));
        } catch (IOException e) {
            // Report metadata is nice to have - never fail the run because of it
            log.warn("Could not write Allure environment.properties: {}", e.getMessage());
        }
    }

    private static void writeEnvironment(Path file) throws IOException {
        Properties env = new Properties();
        env.setProperty("Browser", TestConfig.browser().toString());
        env.setProperty("Headless", String.valueOf(TestConfig.headless()));
        env.setProperty("Base.URL", TestConfig.baseUrl());
        env.setProperty("Java.Version", System.getProperty("java.version"));
        env.setProperty("OS", System.getProperty("os.name") + " " + System.getProperty("os.arch"));
        try (OutputStream out = Files.newOutputStream(file)) {
            env.store(out, "Generated by AllureEnvironmentWriter");
        }
    }
}
